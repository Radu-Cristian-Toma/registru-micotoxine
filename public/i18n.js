// Limba curenta - persistata in localStorage, implicit romana.
let currentLang = localStorage.getItem('appLang') || 'ro';

function setLang(lang) {
  currentLang = lang === 'en' ? 'en' : 'ro';
  localStorage.setItem('appLang', currentLang);
}

// Functie de traducere pentru functia principala t(): comuta intre RO/EN
// dupa limba curenta a interfetei.
function t(path) {
  const parts = path.split('.');
  let node = TRANSLATIONS;
  for (const p of parts) {
    node = node && node[p];
    if (!node) break;
  }
  if (!node || typeof node.ro === 'undefined') return path; // cheie inexistenta - vizibil in dezvoltare
  if (currentLang === 'en' && node.en) return node.en;
  return node.ro;
}

// Functie de traducere SPECIALA pentru buletin: buletinul de analiza este
// un document oficial care poate ajunge la un client din alta tara UE sau
// la export, deci trebuie sa arate ambele limbi SIMULTAN, indiferent de
// limba selectata in restul interfetei - nu comuta, ci afiseaza RO si EN
// impreuna pe acelasi document. Returneaza HTML (RO pe primul rand, EN mai
// mic dedesubt) - foloseste-o doar in contexte unde HTML e permis.
function bt(path) {
  const parts = path.split('.');
  let node = TRANSLATIONS;
  for (const p of parts) {
    node = node && node[p];
    if (!node) break;
  }
  if (!node || typeof node.ro === 'undefined') return path;
  if (!node.en || node.en === node.ro) return node.ro; // fara traducere EN inca - arata doar RO
  // Ambele limbi raman afisate (documentul oficial se citeste si peste granita),
  // dar limba interfeței trece prima: cu interfata pe engleza, eticheta arata
  // intai engleza, apoi romana mai mic. Fara asta, toate ecranele operatorului
  // apareau cu romana principala chiar si pe interfata engleza.
  const primar = currentLang === 'en' ? node.en : node.ro;
  const secundar = currentLang === 'en' ? node.ro : node.en;
  return `${primar}<span class="bulletin-en">${secundar}</span>`;
}

// Traduce bilingv o eticheta de categorie de produs generata pe server
// (vezi db/evaluation.js). Daca eticheta romaneasca nu se potriveste exact
// cu una din harta (ex: categorie noua adaugata ulterior, netradusa inca),
// se afiseaza doar textul romanesc original, fara eroare. Escapeaza HTML
// intern - primeste text brut, returneaza marcaj sigur de inserat.
function btCategory(roLabel) {
  const div = document.createElement('div');
  div.textContent = roLabel || '';
  const safeRo = div.innerHTML;
  const en = TRANSLATIONS.categoryLabels && TRANSLATIONS.categoryLabels[roLabel];
  if (!en) return safeRo;
  const divEn = document.createElement('div');
  divEn.textContent = en;
  const primar = currentLang === 'en' ? divEn.innerHTML : safeRo;
  const secundar = currentLang === 'en' ? safeRo : divEn.innerHTML;
  return `${primar}<span class="bulletin-en">${secundar}</span>`;
}

// Varianta care COMUTA dupa limba curenta (ca t()) - pentru orice context de
// interfata live (dropdown, tabele, antete). Spre deosebire de btCategory
// (folosita DOAR pe buletin, document oficial care arata mereu ambele
// limbi), aici utilizatorul a ales deja o limba, si categoria trebuie sa o
// respecte, nu sa arate mereu amandoua concatenat.
function categoryLabel(roLabel) {
  if (!roLabel) return roLabel;
  if (currentLang === 'en') {
    const en = TRANSLATIONS.categoryLabels && TRANSLATIONS.categoryLabels[roLabel];
    if (en) return en;
  }
  return roLabel;
}

// Varianta text simplu (fara HTML) pentru <option> - elementele option NU
// randeaza marcaj HTML interior, deci acolo trebuie text plat, comutat dupa
// limba curenta, nu concatenat bilingv.
function categoryLabelPlain(roLabel) {
  return categoryLabel(roLabel);
}
